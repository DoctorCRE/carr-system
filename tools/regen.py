"""Regenerate source projections without a provider connection or installed hooks.

Freshness checks in ci.sh test main ancestry, not generated bytes. The gates,
unit, dependency and migration classes own the projections below. Binding also
checks machine wiring; that is deliberately never installed from a PR branch.
"""
from __future__ import annotations

import argparse
import importlib.util
import json
from pathlib import Path
import subprocess
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'ops'))
from git_env import scrubbed_env
from migration_claims import Claims, claims
from migration_source import migration_names

ROOT = Path(__file__).resolve().parents[1]
GENERATORS = (
    ('core rules', ('mcp-server/src/core-rule-ids.js',),
     (sys.executable, 'ops/sync-core-rule-ids.py')),
    ('mutation registry source contracts', ('mcp-server/src/scac-mutation-registry.current.generated.js',),
     ('node', 'ops/scac-mutation-inventory.mjs', '--write-current')),
    ('SQL contract corpus', ('mcp-server/test/f03-design-contract-corpus-plan-postgres.generated.sql',
                            'mcp-server/test/f03-design-contract-corpus-slice-postgres.generated.sql'),
     ('node', 'mcp-server/test/f03-sql-corpus-generator.mjs', '--write')),
)
OUTPUTS = {p for _, paths, _ in GENERATORS for p in paths} | {'ops/config/gate-baseline.json', 'db/schema.sql', 'requirements.lock'}


def run(*argv: str) -> str:
    result = subprocess.run(argv, cwd=ROOT, env=scrubbed_env(), capture_output=True, text=True, timeout=1200)
    if result.returncode:
        raise ValueError(f'{argv[:2]} failed:\n{result.stdout}{result.stderr}')
    if result.stdout:
        print(result.stdout, end='', file=sys.stderr)
    return result.stdout


def module(path: str):
    spec = importlib.util.spec_from_file_location('regen_gate_integrity', ROOT / path)
    assert spec and spec.loader
    loaded = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(loaded)
    return loaded


def regenerate(pr: int | None) -> None:
    pending = migration_names(ROOT) - migration_names(ROOT, 'origin/main')
    branch = run('git', 'branch', '--show-current').strip() if pending and pr is None else None
    peer = claims(pr, branch=branch) if pending else Claims(set(), set(), {})
    command = [sys.executable, 'tools/renumber-at-merge.py']
    for slot in sorted(peer.earlier):
        command += ['--claimed-slot', str(slot)]
    for slot in sorted(peer.occupied):
        command += ['--avoid-slot', str(slot)]
    for _, paths, argv in GENERATORS:
        for path in paths:
            command += ['--generator', path, json.dumps(argv)]
    if pending:
        run(*command)
    for name, _, argv in GENERATORS:
        print(f'regen: {name}', file=sys.stderr)
        run(*argv)

    gate = module('hooks/gate-integrity.py')
    baseline = json.loads((ROOT / 'ops/config/gate-baseline.json').read_text())
    changed = sorted(name for section, current in (('hashes', gate.current()), ('contracts', gate.current_contracts()))
                     for name, digest in current.items() if baseline.get(section, {}).get(name) != digest)
    if changed:
        run(sys.executable, 'hooks/gate-integrity.py', '--bless', *changed)
    if gate.check_baseline():
        raise ValueError('gate baseline still differs; removed gates require deliberate baseline review')

    lock = (ROOT / 'requirements.lock').read_text()
    digest = module('ops/ci-dep-check.py').req_hash()
    if f'# requirements.txt sha256: {digest}' not in lock:
        run(sys.executable, 'ops/ci-dep-check.py', '--write-lock')
    run(sys.executable, 'ops/migration-shadow.py', '--base', 'origin/main', '--write')


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument('--pr', type=int, help='PR number; before opening a PR all existing PRs take precedence')
    parser.add_argument('--list', action='store_true')
    args = parser.parse_args()
    if args.list:
        print(json.dumps({'generators': GENERATORS, 'outputs': sorted(OUTPUTS)}, indent=2))
        return 0
    try:
        run('git', 'merge-base', '--is-ancestor', 'origin/main', 'HEAD')
        regenerate(args.pr)
        return 0
    except (OSError, ValueError, subprocess.SubprocessError) as exc:
        print(f'regen: REFUSED: {exc}', file=sys.stderr)
        return 1


if __name__ == '__main__':
    sys.exit(main())
