def digest(text):
    return hashlib.sha256(text.encode()).hexdigest()


def dump(value):
    return json.dumps(value, indent=2, ensure_ascii=False, sort_keys=True) + "\n"


def call(verb, arguments):
    result = subprocess.run(
        [str(ROOT / "run.sh"), "call", verb, json.dumps(arguments)],
        cwd=ROOT, text=True, capture_output=True, timeout=120, check=True)
    result = json.loads(result.stdout[result.stdout.index("{"):])
    result = result.get("result", result)
    if not result.get("ok"):
        raise ValueError(f"store read failed: {verb}")
    return result


def capture():
    schemas = {v["name"]: v["inputSchema"] for v in call(
        "list-verbs", {"filter": "doctrine"})["verbs"]}
    for verb in ("read-doctrine", "doctrine-sections", "standing-context"):
        if verb not in schemas:
            raise ValueError(f"missing read schema: {verb}")
    memory = call("read-doctrine", {"document": "team-memory"})
    index = [s for s in memory["sections"] if s["section_key"].startswith(TABLE_PREFIX)]
    sections = call("doctrine-sections", {"section_ids": [s["section_id"] for s in index]})
    active = call("standing-context", {"detail": "scopes"})
    snapshot = {
        "schema": "carr-native-rules/v1",
        "corpus_digest": active["corpus_digest"],
        "sections": [
            {"id": s["id"], "key": s["section_key"], "version": s["current_version"],
             "body_text": s["body"]["text"], "text_hash": digest(s["body"]["text"])}
            for s in sorted(sections["sections"], key=lambda s: s["section_key"])],
        "active": sorted(
            ({"id": r["id"], **({"withheld": WITHHELD_REASON} if r["id"] in WITHHELD else {"statement": r["statement"]}), "text_hash": digest(r["statement"])} for r in active["rules"]),
            key=lambda r: r["id"]),
    }
    placements(snapshot)
    return snapshot


def load_snapshot(path):
    return json.loads(path.read_text())


def placements(snapshot):
    rows = []
    for section in snapshot["sections"]:
        if digest(section["body_text"]) != section["text_hash"]:
            raise ValueError("stale placement section hash")
        for line in section["body_text"].splitlines():
            cells = [v.strip() for v in line.strip("|").split("|")]
            if len(cells) == 5 and re.fullmatch(r"[0-9a-f-]{36}", cells[0]):
                rid, version, bucket, text, text_hash = cells
                rows.append(dict(id=rid, version=int(version), bucket=bucket,
                                 text=text, text_hash=text_hash))
    ids = [r["id"] for r in rows]
    if len(ids) != len(set(ids)):
        raise ValueError("duplicate rule placement")
    active = {r["id"]: r["text_hash"] for r in snapshot["active"]}
    statements = {r["id"]: r.get("statement") for r in snapshot["active"]}
    if any((statements[rid] is None and rid not in WITHHELD) or
           (statements[rid] is not None and digest(statements[rid]) != value) for rid, value in active.items()):
        raise ValueError("stale statement hash")
    if len(active) != len(snapshot["active"]) or set(ids) != set(active):
        raise ValueError("active rule coverage differs from placement")
    for row in rows:
        row["statement"] = statements[row["id"]]
        if row["text_hash"] != active[row["id"]]:
            raise ValueError(f"stale placement for {row['id']}")
    return sorted(rows, key=lambda r: r["id"])


def marker(row):
    return row["id"][:8]


def section(row):
    body = row["statement"] if row["statement"] is not None else WITHHELD_REASON + "\n\n" + row["text"]
    return f"### {marker(row)}\n\n{body}\n\n"


def block(existing, content):
    generated = START + "\n" + content.rstrip() + "\n" + END
    if START in existing or END in existing:
        if existing.count(START) != 1 or existing.count(END) != 1:
            raise ValueError("malformed generated guidance block")
        return existing[:existing.index(START)] + generated + existing[existing.index(END) + len(END):]
    return existing + ("\n" if existing else "") + generated + "\n"


def render(snapshot, root):
    rows = placements(snapshot)
    outputs = {}
    homes = {}
    unmatched = []
    path_resolution = {}
    grouped = defaultdict(list)
    descriptions = defaultdict(list)
    nested = defaultdict(list)
    core = NOTICE + "\n\n"
    for row in rows:
        bucket, text = row["bucket"], row["text"]
        if bucket == "CORE":
            core += section(row)
            homes[row["id"]] = "CORE"
        elif bucket == "PATH":
            name = "rule-" + row["id"][:8]
            globs = re.search(r"paths: \[([^]]+)\]", text)[1].split(",")
            globs = [g.strip() for g in globs]
            for glob in globs:
                safe_path(root, glob)
            matches = {}
            for glob in globs:
                matches[glob] = sorted(str(p.relative_to(root)) for p in root.glob(glob)
                                       if p.is_file() and p.name != "AGENTS.md"
                                       and not str(p.relative_to(root)).startswith(".agents/skills/carr-"))
                if not matches[glob]:
                    unmatched.append({"rule": row["id"], "glob": glob, "status": "dormant"})
            path_resolution[row["id"]] = matches
            content = NOTICE + "\n\n" + section(row)
            outputs[f".claude/rules/{name}.md"] = (
                "---\npaths:\n" + "".join(f"  - {json.dumps(g)}\n" for g in globs)
                + "---\n\n" + content)
            folder = re.search(r"Codex nested folder: ([^ ]+)", text)[1].rstrip("/")
            # Preserve dormant proposed scopes instead of inventing a broader matching scope.
            nested[folder + "/AGENTS.md"].append(content)
            for glob in globs:
                prefix = glob.split("*", 1)[0].rstrip("/")
                if matches[glob] and (root / prefix).is_dir() and prefix != folder:
                    nested[prefix + "/AGENTS.md"].append(content)
            homes[row["id"]] = f"PATH:{name}"
        elif bucket in ("SKILL", "JUDGMENT"):
            if bucket == "SKILL":
                name = re.search(r"Skill: ([^.]+)\.", text)[1]
                trigger = re.search(r'Trigger: "([^"]+)"', text)[1]
                descriptions[name].append(trigger)
            else:
                checkpoint = re.search(r"Checkpoint: ([^.]+)\.", text)[1]
                if checkpoint not in CHECKPOINTS:
                    raise ValueError(f"unmapped checkpoint: {checkpoint}")
                name, trigger = CHECKPOINTS[checkpoint]
                descriptions[name] = [trigger]
            grouped[name].append(row)
            homes[row["id"]] = f"{bucket}:carr-{name}"
        elif bucket in ("MECHANICAL", "MERGE or RETIRE"):
            grouped[bucket].append(row)
            homes[row["id"]] = bucket
        else:
            raise ValueError(f"unknown bucket: {bucket}")
    outputs[".claude/rules/carr-core.md"] = core
    target = safe_path(root, "AGENTS.md")
    existing = target.read_text() if target.exists() else ""
    outputs["AGENTS.md"] = block(existing, core)
    for path, contents in nested.items():
        target = safe_path(root, path)
        existing = target.read_text() if target.exists() else ""
        outputs[path] = block(existing, "\n".join(contents))
    for name, members in grouped.items():
        if name in ("MECHANICAL", "MERGE or RETIRE"):
            target = "mechanical" if name == "MECHANICAL" else "merge-retire"
            outputs[f"docs/generated-rules/{target}.md"] = (
                NOTICE + "\n\nProposals only. Existing authority and enforcement remain in place.\n\n"
                + "".join(section(row) for row in members))
            continue
        if not re.fullmatch(r"[a-z0-9][a-z0-9-]{0,58}", name):
            raise ValueError(f"unsafe skill name: {name}")
        description = " ".join(dict.fromkeys(descriptions[name]))
        if members[0]["bucket"] == "SKILL":
            description = "Use when: " + "; ".join(dict.fromkeys(descriptions[name])) + "."
        skill = ("---\nname: carr-" + name + "\ndescription: " + json.dumps(description)
                 + "\n---\n\n" + NOTICE + "\n\n"
                 + "Apply the relevant conditions below. Keep exceptions with their actions; missing evidence means unknown. "
                 + "These are guidance, not a model checker or authorization gate. "
                 + "Joe's live direction and current store authority control conflicts."
                 + "\n\n"
                 + "".join(section(row) for row in members))
        outputs[f".claude/skills/carr-{name}/SKILL.md"] = skill
        outputs[f".agents/skills/carr-{name}/SKILL.md"] = skill
    outputs = {p: text.rstrip("\n") + "\n" if not p.endswith("AGENTS.md") else text for p, text in outputs.items()}
    report = dict(withheld_statements={rid: WITHHELD_REASON for rid in sorted(WITHHELD)},
                  rules={r["id"]: {"version": r["version"], "sha256": r["text_hash"]} for r in rows},
                  nested_agents=sorted(nested),
                  schema="carr-native-rules-manifest/v1", homes=homes,
                  unmatched_globs=unmatched, path_resolution=path_resolution,
                  active_glob_count=sum(bool(paths) for matches in path_resolution.values() for paths in matches.values()),
                  dormant_glob_count=len(unmatched),
                  outputs=sorted(outputs))
    return outputs, report


def stale_outputs(root, outputs):
    stale = [p for p, text in outputs.items()
             if not (root / p).is_file() or (root / p).read_text() != text]
    for base in (".claude/rules", ".claude/skills", ".agents/skills", "docs/generated-rules"):
        for path in (root / base).rglob("*.md"):
            rel = str(path.relative_to(root))
            if NOTICE in path.read_text() and rel not in outputs:
                stale.append(rel)
    for path in root.rglob("AGENTS.md"):
        rel = str(path.relative_to(root))
        if "node_modules" not in path.parts and NOTICE in path.read_text() and rel not in outputs:
            stale.append(rel)
    manifest = root / REPORT
    if manifest.is_file():
        previous = json.loads(manifest.read_text())
        stale.extend(p for p in previous["outputs"] if p not in outputs and (root / p).exists())
    return sorted(set(stale))


def safe_path(root, name):
    parts = name.split("/")
    if (not name or Path(name).is_absolute() or any(p in ("", ".", "..", ".git") for p in parts)):
        raise ValueError(f"unsafe output path: {name}")
    path = root / name
    for ancestor in [path, *path.parents]:
        if ancestor == root:
            break
        if ancestor.is_symlink():
            raise ValueError(f"symlink output path: {name}")
    if not path.resolve().is_relative_to(root.resolve()):
        raise ValueError(f"escaping output path: {name}")
    return path


def allowed_output(name, nested):
    return (name in (SNAPSHOT, REPORT, "AGENTS.md",
                     "docs/generated-rules/mechanical.md", "docs/generated-rules/merge-retire.md")
            or name in nested
            or re.fullmatch(r"\.claude/rules/[a-z0-9-]+\.md", name)
            or re.fullmatch(r"\.(?:agents|claude)/skills/carr-[a-z0-9-]+/SKILL\.md", name))


@contextmanager
def output_parent(root, name):
    # Directory descriptors pin each parent; O_NOFOLLOW also closes mutation-time symlink races.
    fd = os.open(root, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW)
    try:
        for part in Path(name).parts[:-1]:
            try:
                os.mkdir(part, dir_fd=fd)
            except FileExistsError:
                pass
            child = os.open(part, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW, dir_fd=fd)
            os.close(fd)
            fd = child
        yield fd
    finally:
        os.close(fd)


def write_outputs(root, outputs):
    manifest = safe_path(root, REPORT)
    previous = json.loads(manifest.read_text()) if manifest.is_file() else {"outputs": []}
    names = set(outputs) | set(previous["outputs"])
    current = json.loads(outputs[REPORT]) if REPORT in outputs else {"nested_agents": []}
    nested = set(current.get("nested_agents", [])) | set(previous.get("nested_agents", []))
    # Legacy manifests listed nested files in outputs before nested_agents was explicit.
    if "nested_agents" not in previous:
        nested.update(n for n in previous["outputs"] if n.endswith("/AGENTS.md"))
    if REPORT not in outputs:
        nested.update(n for n in outputs if n.endswith("/AGENTS.md"))
    changes = {}
    for name in sorted(names):
        path = safe_path(root, name)
        if not allowed_output(name, nested):
            raise ValueError(f"unowned output path: {name}")
        if path.exists() and not path.is_file():
            raise ValueError(f"output is not a file: {name}")
        old = path.read_text() if path.exists() else ""
        if name.endswith("/SKILL.md") and path.parent.exists():
            if not path.is_file() or NOTICE not in old or name not in previous["outputs"]:
                raise ValueError(f"foreign skill directory: {name}")
        if name in outputs:
            content = outputs[name]
            if name.endswith("AGENTS.md"):
                generated = content[content.index(START):content.index(END) + len(END)]
                if block(old, generated[len(START): -len(END)].strip()) != content:
                    raise ValueError(f"write outside generated block: {name}")
            elif old and NOTICE not in old and name not in (REPORT, SNAPSHOT):
                raise ValueError(f"foreign output: {name}")
            changes[name] = content
        elif old:
            if NOTICE not in old:
                raise ValueError(f"refusing to remove foreign output: {name}")
            if name.endswith("AGENTS.md"):
                if old.count(START) != 1 or old.count(END) != 1:
                    raise ValueError(f"malformed generated block: {name}")
                changes[name] = old[:old.index(START)] + old[old.index(END) + len(END):]
            else:
                changes[name] = None
    for name, content in changes.items():
        with output_parent(root, name) as fd:
            leaf = Path(name).name
            if content is None:
                os.unlink(leaf, dir_fd=fd)
            else:
                flags = os.O_WRONLY | os.O_CREAT | os.O_TRUNC | os.O_NOFOLLOW
                with os.fdopen(os.open(leaf, flags, 0o644, dir_fd=fd), "w") as stream:
                    stream.write(content)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--from-store", action="store_true", help="read live placement and catalog; requires tiktoken")
    parser.add_argument("--check", action="store_true", help="verify against committed snapshot offline")
    args = parser.parse_args()
    snapshot = capture() if args.from_store else load_snapshot(ROOT / SNAPSHOT)
    outputs, report = render(snapshot, ROOT)
    core = outputs[".claude/rules/carr-core.md"]
    chain = START + "\n" + core.rstrip() + "\n" + END + "\n"
    if args.from_store:
        import tiktoken
        snapshot["core_measurement"] = {
            "tokenizer": "cl100k_base", "sha256": digest(chain),
            "original_budget": 1500, "over_original_budget": len(tiktoken.get_encoding("cl100k_base").encode(chain)) >= 1500,
            "tokens": len(tiktoken.get_encoding("cl100k_base").encode(chain))}
    measured = snapshot["core_measurement"]
    if (measured["sha256"] != digest(chain) or not 0 < measured["tokens"]
            or measured["tokenizer"] != "cl100k_base"):
        raise ValueError("CORE measurement stale; regenerate from store with tiktoken")
    print(f"CORE added startup chain: {measured['tokens']} cl100k_base tokens per adapter; native Claude token count unmeasured")
    startup = {"AGENTS.md": outputs["AGENTS.md"],
               "CLAUDE.md": (ROOT / "CLAUDE.md").read_text(),
               ".claude/rules/carr-core.md": core}
    if args.from_store:
        report["startup_measurement"] = {
            "tokenizer": "cl100k_base",
            "files": {p: {"sha256": digest(t), "tokens": len(tiktoken.get_encoding("cl100k_base").encode(t))}
                      for p, t in startup.items()},
            "tokens": len(tiktoken.get_encoding("cl100k_base").encode("\n".join(startup.values())))}
    else:
        report["startup_measurement"] = json.loads((ROOT / REPORT).read_text())["startup_measurement"]
        if any(report["startup_measurement"]["files"][p]["sha256"] != digest(t) for p, t in startup.items()):
            raise ValueError("startup measurement stale; regenerate from store")
    print(f"Full startup chain: {report['startup_measurement']['tokens']} cl100k_base tokens")
    print(f"Coverage: {len(report['homes'])} active IDs, one primary home each; provider copies are adapters")
    for item in report["unmatched_globs"]:
        print(f"UNMATCHED {item['rule']}: {item['glob']}")
    outputs[REPORT] = dump(report)
    if args.check:
        if args.from_store and dump(snapshot) != (ROOT / SNAPSHOT).read_text():
            raise ValueError("committed snapshot differs from live store")
        stale = stale_outputs(ROOT, outputs)
        if stale:
            raise ValueError("stale generated files: " + ", ".join(stale))
    else:
        outputs[SNAPSHOT] = dump(snapshot)
        write_outputs(ROOT, outputs)


if __name__ == "__main__":
    main()
