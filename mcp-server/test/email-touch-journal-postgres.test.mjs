import test from 'node:test';
import assert from 'node:assert/strict';
import { existsSync, readFileSync } from 'node:fs';
import { randomUUID } from 'node:crypto';
import pg from 'pg';
const { Client } = pg;
import { acquireDisposablePostgres } from './helpers/disposable-postgres.mjs';
import { emailTouchJournalTools } from '../src/email-touch-journal.js';
import { Validator } from '@cfworker/json-schema';

test('journal custody, replay, privilege denials and append-only outcomes in PostgreSQL', async () => {
 const bin=['/opt/homebrew/opt/postgresql@18/bin','/usr/lib/postgresql/18/bin'].find(p=>existsSync(p+'/initdb'));
 assert.ok(bin,'PostgreSQL 18 required');
 const fixture=await acquireDisposablePostgres({prefix:'email-journal-',pgCtl:bin+'/pg_ctl'});
 await fixture.run(bin+'/initdb',['-D',fixture.root+'/data','-U','fixture','--auth=trust','--no-locale']);
 await fixture.run(bin+'/pg_ctl',['-D',fixture.root+'/data','-l',fixture.root+'/server.log','-o',`-k ${fixture.root} -h '' -p 55474`,'-w','start']);
 const db=new Client({host:fixture.root,port:55474,database:'postgres',user:'fixture'});
 try {
  await db.connect();
  await db.query(`create extension pgcrypto; create schema ops;
   create role carr_reader; create role carr_writer; create role carr_authority; create role carr_jobs; create role dot_reader;
   create table actor(id uuid primary key,slug text,active boolean default true);
   create table party(id uuid primary key,deleted_at timestamptz);
   create table event(actor_id uuid,verb text,idempotency_key text);
   create table refs(subject_type text,subject_id uuid,ref text,party_id uuid,merged boolean default false);
   create view v_ref_index as select * from refs;
   grant usage on schema ops to carr_writer; grant select on v_ref_index,party to carr_writer;
   create function ops.portfolio_writer_actor_id() returns uuid language sql as $q$ select id from public.actor where slug=current_setting('carr.acting_actor_slug') $q$;
   create function ops.scac_current_grant_contract() returns jsonb language sql as $q$ select '{"secdef_execute":[]}'::jsonb $q$;`);
  const actor=randomUUID(),target=randomUUID(),party=randomUUID(),key=randomUUID();
  await db.query("insert into actor values ($1,'joe-local',true)",[actor]);
  await db.query('insert into party values ($1,null)',[party]);
  await db.query("insert into refs values ('client',$1,'C-901',$2,false)",[target,party]);
  await db.query(readFileSync(new URL('../../migrations/1158_email_touch_journal.sql',import.meta.url),'utf8'));
  await db.query("select set_config('carr.acting_actor_slug','joe-local',false),set_config('carr.sponsoring_human_slug','joe',false),set_config('carr.organization_tenant_id','carr-internal',false)");
  let liveRelease='a'.repeat(40);
  const tools=emailTouchJournalTools({withEnvelope:(_c,_a,_v,_args,fn)=>fn(),ToolError:class extends Error{constructor(p){super(p.error)}},release:()=>liveRelease,principal:()=> 'joe'});
  const args={idempotency_key:randomUUID(),principal_slug:'joe',producer_sha:'a'.repeat(40),mailbox_scope_hash:'b'.repeat(64),execution_id:randomUUID(),source_id:'outlook-intake:v1:'+'c'.repeat(64),source_version:'sha256:'+'d'.repeat(64),projection_digest:'d'.repeat(64),message_hash:'e'.repeat(64),proposals:[{original_key:key,ref:'C-901',kind:'email_in',occurred_at:'2026-11-01T12:00:00.000Z'}]};
  await db.query('set role carr_writer');
  const capture=()=>tools['capture-email-touch-journal'].handler(db,{id:actor,slug:'joe-local'},structuredClone(args));
  const first=await capture();
  assert.equal(first.ok,true); assert.equal(first.reference,'sha256:'+first.digest);
  const journal=JSON.parse(Buffer.from(first.raw_base64,'base64'));
  assert.equal(journal.expected[0].target_id,target);
  assert.equal(journal.expected_count,1);
  assert.deepEqual(await capture(),first);
  for(const sql of ['update ops.email_touch_expectation_journal set raw=raw','delete from ops.email_touch_expectation_journal','truncate ops.email_touch_expectation_journal',"insert into ops.email_touch_expectation_journal(tenant) values ('carr-internal')"])
   await assert.rejects(db.query(sql),/permission denied/);
  const changed={...args,source_version:'sha256:'+'f'.repeat(64),projection_digest:'f'.repeat(64)};
  await assert.rejects(tools['capture-email-touch-journal'].handler(db,{id:actor,slug:'joe-local'},changed),/conflict/);
  const outcome={idempotency_key:randomUUID(),reference:first.reference,observations:[{observation_id:randomUUID(),original_key:key,status:'uncertain',activity_id:null,error_code:'timeout'}]};
  const record=()=>tools['record-email-touch-journal-outcome'].handler(db,{id:actor,slug:'joe-local'},outcome);
  assert.equal((await record()).ok,true); assert.equal((await record()).ok,true);
  outcome.observations[0].status='acknowledged';
  await assert.rejects(record(),/conflict/);
  liveRelease='f'.repeat(40);
  await assert.rejects(capture(),/release_mismatch/);
  await assert.rejects(record(),/release_mismatch/);
  liveRelease='a'.repeat(40);
  await db.query("select set_config('carr.organization_tenant_id','foreign',false)");
  await assert.rejects(capture(),/identity_refused/);
  await db.query("select set_config('carr.organization_tenant_id','carr-internal',false)");
  await db.query('reset role');
  await db.query('update party set deleted_at=clock_timestamp() where id=$1',[party]);
  await db.query('set role carr_writer');
  assert.deepEqual(await capture(),first,'target lifecycle changes cannot rewrite frozen membership');
  await db.query('reset role');
  await db.query('update party set deleted_at=null where id=$1',[party]);
  const targets=Array.from({length:500},(_,i)=>({id:randomUUID(),ref:'C-'+(1000+i)}));
  await db.query(`insert into refs select 'client',x.id,x.ref,$2::uuid,false
   from jsonb_to_recordset($1::jsonb) x(id uuid,ref text)`,[JSON.stringify(targets),party]);
  const batch={...args,idempotency_key:randomUUID(),mailbox_scope_hash:'f'.repeat(64),proposals:targets.map(t=>({original_key:randomUUID(),ref:t.ref,kind:'email_in',occurred_at:args.proposals[0].occurred_at}))};
  const validator=new Validator(tools['capture-email-touch-journal'].inputSchema);
  assert.equal(validator.validate(batch).valid,true);
  assert.equal(validator.validate({...batch,proposals:[...batch.proposals,batch.proposals[0]]}).valid,false);
  assert.equal(validator.validate({...batch,proposals:[]}).valid,false);
  await db.query('set role carr_writer');
  let queries=0;
  const counted={query:(...q)=>{queries++;return db.query(...q);}};
  const big=await tools['capture-email-touch-journal'].handler(counted,{id:actor,slug:'joe-local'},batch);
  assert.equal(queries,3,'resolution and custody use fixed round trips for 500 effects');
  assert.equal(JSON.parse(Buffer.from(big.raw_base64,'base64')).expected_count,500);
  await db.query('reset role');
  await assert.rejects(db.query('delete from ops.email_touch_expectation_journal'),/immutable/);
  await assert.rejects(db.query('truncate ops.email_touch_journal_outcome'),/immutable/);
  const saved=(await db.query('select raw from ops.email_touch_expectation_journal where digest=$1',[first.digest])).rows[0].raw;
  assert.equal(saved.toString('base64'),first.raw_base64);
 } finally {await db.end();await fixture.close();}
});
