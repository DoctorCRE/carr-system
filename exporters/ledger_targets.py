def _header(title, ledger, imported, subtitle):
    total = SOURCE_ENTRY_TOTALS[ledger]
    return [
        f"# {title}",
        "",
        "> **GENERATED from the CARR record layer — do not hand-edit.**",
        f"> {subtitle}",
        ">",
        f"> **Coverage: {imported} of {total} entries from the source ledger.** "
        f"{PARKED_NOTE[ledger]}",
        ">",
        "> To add an entry, do not edit this file — record it in the record layer and this "
        "render refreshes. Pre-conversion original frozen at "
        "`CARR AI/Archive/snapshots/2026-08-01-*-freeze.zip`.",
        "",
    ]


def _fetch(cur, ledger):
    cur.execute(
        "select entry_id, entry_date, author, subject_ref, subject_name, subject_type, "
        "       summary, detail "
        "  from v_md_ledger_entry where ledger = %s "
        " order by entry_date desc, entry_id, subject_ref", (ledger,))
    return cur.fetchall()


def _group(rows):
    """One block per ENTRY, listing every subject it touched.

    The import writes one activity row per (entry, subject) so each subject's own
    timeline carries the entry — that is what "events on the subjects they touched"
    means. But the LEDGER reads as one line per hunt, not five, so the render
    regroups. summary/detail are identical across an entry's rows by construction.
    """
    out = []
    for r in rows:
        entry_id, date, author, ref, name, stype, summary, detail = r
        if out and out[-1]["entry_id"] == entry_id:
            out[-1]["subjects"].append((ref, name, stype))
        else:
            out.append({"entry_id": entry_id, "date": date, "author": author,
                        "summary": summary, "detail": detail,
                        "subjects": [(ref, name, stype)]})
    return out


def _render(tmp_path, cur, ledger, title, subtitle):
    entries = _group(_fetch(cur, ledger))
    lines = _header(title, ledger, len(entries), subtitle)

    if not entries:
        lines += ["*No entries imported yet.*", ""]
    for e in entries:
        lines += [f"## {e['date']} — {e['summary']}", "",
                  f"*Entry `{e['entry_id']}` · recorded by {e['author']} · "
                  f"{len(e['subjects'])} subject(s) touched*", ""]
        for ref, name, stype in e["subjects"]:
            lines.append(f"- `{ref}` — {name} ({stype})")
        lines += ["", e["detail"], ""]

    lines += [f"*Exported: {datetime.now(timezone.utc).isoformat()} · "
              f"{len(entries)} entr(y/ies)*", ""]
    tmp_path.write_text("\n".join(lines))
    # (count, rows) — the shape every builder in targets.py returns.
    return len(entries), [[e["entry_id"], str(e["date"]), e["author"],
                           ", ".join(s[0] for s in e["subjects"])] for e in entries]


def build_hunt_ledger(tmp_path, cur):
    return _render(
        tmp_path, cur, "hunt-ledger", "Vendor Discovery — Hunt Ledger",
        "The run-log for the weekly vendor-discovery hunt (engine.md Section 5). Read before "
        "each hunt so nobody is re-proposed.")


def build_reciprocity(tmp_path, cur):
    return _render(
        tmp_path, cur, "deals-reciprocity", "Reciprocity Ledger — vendors you plug in most",
        "Who sends us business and what we owe back. The referral RELATIONSHIPS themselves are "
        "the intro graph (`who-do-we-know`); this ledger carries the standing arrangements that "
        "sit on top of them.")
