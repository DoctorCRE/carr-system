-- rollback: forward-only — deleting the row would un-register a control a rule approval may then cite; retire it with a guarded retirement migration like 0836
-- 0868_register_unfiled_bug_stop_gate_control.sql
--
-- REGISTER THE ENFORCEMENT CONTROL `unfiled_bug`.
--
-- WHY THIS EXISTS. Rule 19ebbeb3 (a detected bug is recorded and addressed in
-- the same session, never stepped over) and rule 1b8e7f43 (a refusal or block
-- the session hit is filed, not narrated) had no carrying control: both were
-- judgment-only, and on 2026-10-12 Joe watched a session name a brittle test,
-- a rule-boot misfire and a re-arm defect and file one of the three. The hook
-- that now enforces them, hooks/unfiled-bug-stop-gate.py, is a Stop gate with
-- its own selftest, ops/unfiled-bug-stop-gate-selftest.py, which ops/ci.sh runs
-- on every push. The repository declares the control in
-- ops/config/rule-enforcement-map.json and
-- ops/config/control-enforcement-classes.v1.json; this migration is the
-- production projection of that declaration, rendered by
--   ops/sync_control_catalog.py --render-control unfiled_bug
-- and never hand-written, because ops/control-catalog-parity-gate.py compares
-- the catalog row byte-for-byte against the map.
--
-- WHAT THIS DOES NOT DO. It adds no rule_control_binding row and changes no
-- rule's approval: binding 19ebbeb3 and 1b8e7f43 to this control in production
-- stays a separate approval act. It only makes the control exist so that
-- approval can name it.

-- GENERATED by ops/sync_control_catalog.py; never hand-edit.
insert into ops.enforcement_control_catalog
    (control_key, implementation_ref, test_ref, enforcement_class, installed, verified_at, updated_at)
values ('unfiled_bug', 'hooks/unfiled-bug-stop-gate.py', 'ops/unfiled-bug-stop-gate-selftest.py', 'stop_gate', true, now(), now())
on conflict (control_key) do update set
    implementation_ref = excluded.implementation_ref,
    test_ref           = excluded.test_ref,
    enforcement_class  = excluded.enforcement_class,
    installed          = excluded.installed,
    verified_at        = excluded.verified_at,
    updated_at         = now();

-- post-conditions
do $$
begin
  if not exists (select 1 from ops.enforcement_control_catalog
                  where control_key = 'unfiled_bug'
                    and installed
                    and verified_at is not null
                    and enforcement_class = 'stop_gate'
                    and implementation_ref = 'hooks/unfiled-bug-stop-gate.py'
                    and test_ref = 'ops/unfiled-bug-stop-gate-selftest.py') then
    raise exception '0868 FAILED: unfiled_bug is not an installed, verified stop_gate after the insert';
  end if;
end $$;
