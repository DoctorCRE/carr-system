-- 0753_eval_receipt_control.sql
--
-- Register the carrying control for rule 6cbaa63a-be57-4c2e-955f-4ea7b5c0405d
-- ("every LLM-steering change ships an eval receipt"), taught with
-- enforcement_home=gate and carrying_control 'eval_receipt CI check'.
-- approve-rule refuses a control that ops.enforcement_control_catalog does not
-- carry installed and verified in an enforcing class; this is that row.
--
-- WHAT THE CONTROL IS. ops/check-eval-receipt.py runs in ops/ci.sh's gates
-- class, which is part of the required `ops/ci.sh --strict` context on the
-- main ruleset. A pull request that changes a surface registered in
-- evals/surfaces.json without a valid evals/<surface>/receipt.json changed in
-- the same PR, or a reasoned no-eval line in its body, turns that context red,
-- and a red head cannot merge. deny_gate, the same class pr_only_main_ruleset
-- carries for the same reason.
--
-- DECLARED BESIDE THE MAP. The row is declared under controls_absent_from_the_map
-- in ops/config/control-enforcement-classes.v1.json, because
-- audits/guidance-situation-curation-review.v1.json still pins
-- ops/config/rule-enforcement-map.json by sha256 while that review is proposed.
--
-- NUMBER CLAIMED BY A FRESH SCAN of every remote ref: highest claimed 0752
-- (open PR branches), so 0753.
--
-- No SCAC successor: this inserts one catalog row and changes no function,
-- grant, role or relation the mutation registry projects.
--
-- NO explicit begin/commit: the runner wraps every migration from 0339_
-- onward in a single transaction.
--
-- Rendered by ops/sync_control_catalog.py --render-control eval_receipt; the
-- block below is compared byte-for-byte by ops/check-eval-receipt-selftest.py.

-- GENERATED by ops/sync_control_catalog.py; never hand-edit.
insert into ops.enforcement_control_catalog
    (control_key, implementation_ref, test_ref, enforcement_class, installed, verified_at, updated_at)
values ('eval_receipt', 'ops/check-eval-receipt.py; ops/ci.sh; evals/surfaces.json', 'ops/check-eval-receipt-selftest.py', 'deny_gate', true, now(), now())
on conflict (control_key) do update set
    implementation_ref = excluded.implementation_ref,
    test_ref           = excluded.test_ref,
    enforcement_class  = excluded.enforcement_class,
    installed          = excluded.installed,
    verified_at        = excluded.verified_at,
    updated_at         = now();

do $eval_receipt_seeded$
begin
  if not exists (select 1 from ops.enforcement_control_catalog
                  where control_key = 'eval_receipt'
                    and installed and verified_at is not null
                    and enforcement_class = 'deny_gate') then
    raise exception '0753 FAILED: eval_receipt is not an installed, verified deny_gate';
  end if;
end $eval_receipt_seeded$;
