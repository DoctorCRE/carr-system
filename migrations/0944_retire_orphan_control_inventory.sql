-- rollback: forward-only; restore implementations and source declarations before restoring retired controls.
-- expand-contract: reconcile the catalog with PR #2195's source inventory; preserve rule records and receipts.
-- lock-review: ten primary-key deletions and one retained control upsert; binding and active-approval guards remain active.
do $retire_orphan_controls$
declare
  key text;
  bound integer;
  claimed integer;
begin
  foreach key in array array[
    'canonical_edit',
    'control-plane-workflow-manifest',
    'costar_lane',
    'draft_export_read',
    'github-burst-guard',
    'model_floor',
    'one_repo',
    'verification_status',
    'weekend_quiet',
    'weekly_social_route'
  ] loop
    select count(*) into bound
      from ops.rule_control_binding where control_key = key;
    if bound > 0 then
      raise exception '0944 REFUSED: % still has % rule binding(s)', key, bound;
    end if;

    select count(*) into claimed
      from ops.rule_approval_receipt ar
      join rule r on r.id = ar.rule_id and r.status = 'active'
     where key = any(ar.requested_control_keys);
    if claimed > 0 then
      raise exception '0944 REFUSED: % backs % active approved rule(s)', key, claimed;
    end if;

    delete from ops.enforcement_control_catalog where control_key = key;
  end loop;
end $retire_orphan_controls$;

