// One guard for every inventory CLI writer. Render functions stay pure for
// byte-exact historical checks; only source writes cross this seam.
import { execFileSync } from 'node:child_process';
import { realpathSync } from 'node:fs';
import { writeFile } from 'node:fs/promises';
import { basename, dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = realpathSync(resolve(import.meta.dirname, '..'));
// Sealed artifacts live only under these source roots. Exports and other
// targets keep the plain filesystem writer and need no live Git context.
const SOURCE_ARTIFACT = /^(?:migrations\/.*\.sql|mcp-server\/src\/scac-mutation-registry(?:\.v[1-9][0-9]*|\.current)?\.generated\.js)$/;

export async function writeIntegratedArtifact(target, content) {
  const requested = target instanceof URL ? fileURLToPath(target) : resolve(String(target));
  const path = join(realpathSync(dirname(requested)), basename(requested));
  const inside = relative(repo, path).split(sep).join('/');
  if (!SOURCE_ARTIFACT.test(inside)) return writeFile(path, content);
  try {
    // The owned check and the write are one operation in the integration owner.
    execFileSync('python3', [resolve(repo, 'tools/integration_candidate.py'), '--write', path],
      { cwd: repo, input: content, stdio: ['pipe', 'ignore', 'ignore'] });
  } catch {
    // The generated bytes and child diagnostics can contain internal inputs.
    throw new Error('integration generation refused: refresh main, allocate a fresh successor, then render');
  }
}
